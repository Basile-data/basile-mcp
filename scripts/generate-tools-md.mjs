#!/usr/bin/env node
// Génère docs/TOOLS.md et le résumé des outils du README à partir de tools.json.
//
//   node scripts/generate-tools-md.mjs           réécrit docs/TOOLS.md et le README
//   node scripts/generate-tools-md.mjs --check   échoue (code 1) si l'un des deux n'est pas à jour
//
// Le script vérifie aussi tools.json : chaque outil doit avoir un titre et ses
// annotations (readOnlyHint, destructiveHint, idempotentHint, openWorldHint).
//
// Aucune dépendance : Node.js 20 ou plus récent suffit.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const RACINE = join(dirname(fileURLToPath(import.meta.url)), '..')
const TOOLS_JSON = join(RACINE, 'tools.json')
const TOOLS_MD = join(RACINE, 'docs', 'TOOLS.md')
const README = join(RACINE, 'README.md')

const BLOCS = {
	fr: ['<!-- outils:debut (généré par scripts/generate-tools-md.mjs) -->', '<!-- outils:fin -->'],
	en: ['<!-- tools:start (generated by scripts/generate-tools-md.mjs) -->', '<!-- tools:end -->'],
}
const FACTURATIONS = ['gratuit', 'credits', 'quota_export', 'solde_enrichissement']
const ANNOTATIONS = ['readOnlyHint', 'destructiveHint', 'idempotentHint', 'openWorldHint']
const NOM_OUTIL = /^[a-z0-9_]{1,64}$/

const verifier = process.argv.includes('--check')
const data = JSON.parse(readFileSync(TOOLS_JSON, 'utf8'))

function echec(message) {
	console.error(`tools.json : ${message}`)
	process.exit(1)
}

// ---------------------------------------------------------------------------
// Contrôle de tools.json
// ---------------------------------------------------------------------------

function texte(objet, champ, ou) {
	if (typeof objet[champ] !== 'string' || !objet[champ].trim()) echec(`${ou} : champ "${champ}" absent ou vide.`)
}

for (const champ of ['name', 'title', 'version', 'url', 'websiteUrl']) texte(data.server ?? {}, champ, 'server')
if (!Array.isArray(data.families) || !data.families.length) echec('aucune famille.')
if (!Array.isArray(data.tools) || !data.tools.length) echec('aucun outil.')

const idsFamilles = new Set()
for (const famille of data.families) {
	for (const champ of ['id', 'title', 'title_en', 'summary', 'summary_en']) texte(famille, champ, `famille ${famille.id ?? '?'}`)
	if (idsFamilles.has(famille.id)) echec(`famille ${famille.id} en double.`)
	idsFamilles.add(famille.id)
}

const noms = new Set()
for (const outil of data.tools) {
	const ou = `outil ${outil.name ?? '?'}`
	for (const champ of ['name', 'title', 'family', 'summary', 'summary_en', 'description', 'billing', 'cost', 'cost_en']) {
		texte(outil, champ, ou)
	}
	if (!NOM_OUTIL.test(outil.name)) echec(`${ou} : nom invalide (64 caractères au plus, minuscules, chiffres et _).`)
	if (noms.has(outil.name)) echec(`${ou} : en double.`)
	noms.add(outil.name)
	if (!idsFamilles.has(outil.family)) echec(`${ou} : famille inconnue "${outil.family}".`)
	if (!FACTURATIONS.includes(outil.billing)) echec(`${ou} : facturation inconnue "${outil.billing}".`)
	for (const cle of ANNOTATIONS) {
		if (typeof outil.annotations?.[cle] !== 'boolean') echec(`${ou} : annotation ${cle} absente.`)
	}
	if (!Array.isArray(outil.parameters)) echec(`${ou} : "parameters" doit être une liste.`)
	for (const parametre of outil.parameters) {
		for (const champ of ['name', 'type', 'description']) texte(parametre, champ, `${ou}, paramètre ${parametre.name ?? '?'}`)
		if (typeof parametre.required !== 'boolean') echec(`${ou}, paramètre ${parametre.name} : "required" doit valoir true ou false.`)
	}
}

const familles = data.families.map((famille) => ({
	...famille,
	outils: data.tools.filter((outil) => outil.family === famille.id),
}))
for (const famille of familles) if (!famille.outils.length) echec(`famille ${famille.id} sans outil.`)

// ---------------------------------------------------------------------------
// Mise en forme
// ---------------------------------------------------------------------------

/** Texte qui tient dans une cellule de tableau Markdown. */
function cellule(valeur) {
	return String(valeur ?? '')
		.replace(/\|/g, '\\|')
		.replace(/\s*\n\s*/g, ' ')
		.trim()
}

/** Ancre GitHub d'un titre. */
function ancre(titre) {
	return titre
		.toLowerCase()
		.replace(/[^\p{L}\p{N} _-]/gu, '')
		.replace(/ /g, '-')
}

/** Première lettre en minuscule, pour un texte qui suit deux points. */
function minuscule(texte) {
	return texte.charAt(0).toLowerCase() + texte.slice(1)
}

function compte(nombre, singulier, pluriel) {
	return `${nombre} ${nombre === 1 ? singulier : pluriel}`
}

const lectureSeule = (outils) => outils.filter((outil) => outil.annotations.readOnlyHint).length
const gratuits = (outils) => outils.filter((outil) => outil.billing === 'gratuit').length
const principaux = (outil) => outil.parameters.filter((parametre) => parametre.main !== false)
const listeParametres = (outil) =>
	principaux(outil).length ? principaux(outil).map((parametre) => `\`${parametre.name}\``).join(', ') : 'aucun'
const listeParametresEn = (outil) =>
	principaux(outil).length ? principaux(outil).map((parametre) => `\`${parametre.name}\``).join(', ') : 'none'
const nature = (outil) => (outil.annotations.readOnlyHint ? 'lecture seule' : 'consomme')
const natureEn = (outil) => (outil.annotations.readOnlyHint ? 'read-only' : 'consumes')
const annotations = (outil) => ANNOTATIONS.map((cle) => `\`${cle}: ${outil.annotations[cle]}\``).join(', ')

const total = data.tools.length
const totaux = {
	outils: compte(total, 'outil', 'outils'),
	familles: compte(familles.length, 'famille', 'familles'),
	tools: compte(total, 'tool', 'tools'),
	families: compte(familles.length, 'family', 'families'),
}

// ---------------------------------------------------------------------------
// docs/TOOLS.md
// ---------------------------------------------------------------------------

function construireToolsMd() {
	const lignes = [
		'<!-- Généré par scripts/generate-tools-md.mjs à partir de tools.json. Ne pas modifier à la main. -->',
		'',
		'# Outils du serveur MCP de Basile',
		'',
		'**Français** · [English](#english)',
		'',
		`La version ${data.server.version} du serveur MCP de Basile (\`${data.server.url}\`) expose **${totaux.outils}** en **${totaux.familles}**. Cette page est générée à partir de [\`tools.json\`](../tools.json), qui reprend le titre et les annotations de chaque outil tels que le serveur les déclare.`,
		'',
		'Retour au [README](../README.md).',
		'',
		'| Famille | Outils | Lecture seule | Gratuits |',
		'| --- | ---: | ---: | ---: |',
		...familles.map(
			(famille) =>
				`| [${famille.title}](#${ancre(famille.title)}) | ${famille.outils.length} | ${lectureSeule(famille.outils)} | ${gratuits(famille.outils)} |`
		),
		`| **Total** | **${total}** | **${lectureSeule(data.tools)}** | **${gratuits(data.tools)}** |`,
		'',
		'## Comment lire cette page',
		'',
		"- **Lecture seule** (`readOnlyHint: true`) : l'outil ne fait que lire la base Basile. Votre client peut le lancer sans demander de confirmation. Une recherche consomme tout de même des crédits, indiqués dans la colonne Coût.",
		"- **Consomme** (`readOnlyHint: false`) : l'outil débite le quota d'export de votre offre ou votre solde d'enrichissement. Votre client peut vous demander de confirmer avant de le lancer.",
		"- **Aucun outil n'est destructif** (`destructiveHint: false` partout) : le serveur ne modifie ni ne supprime rien chez vous.",
		"- **`idempotentHint`** : rappeler l'outil avec les mêmes paramètres ne change rien de plus. **`openWorldHint`** : l'outil interroge le service Basile, hors de votre client.",
		"- **Comptez avant d'extraire** : `basile_count` est gratuit et exact, alors que le total rendu par une recherche s'arrête à 100 000.",
	]

	for (const famille of familles) {
		lignes.push(
			'',
			`## ${famille.title}`,
			'',
			`${famille.summary}`,
			'',
			'| Outil | Titre | Coût | Nature |',
			'| --- | --- | --- | --- |',
			...famille.outils.map(
				(outil) =>
					`| [\`${outil.name}\`](#${ancre(outil.name)}) | ${cellule(outil.title)} | ${cellule(outil.cost)} | ${nature(outil)} |`
			)
		)
		for (const outil of famille.outils) {
			lignes.push('', `### ${outil.name}`, '', `**${outil.title}** · ${outil.cost} · ${nature(outil)}`, '', outil.description, '')
			if (outil.parameters.length) {
				lignes.push(
					'| Paramètre | Type | Requis | Description |',
					'| --- | --- | --- | --- |',
					...outil.parameters.map(
						(parametre) =>
							`| \`${parametre.name}\` | \`${cellule(parametre.type)}\` | ${parametre.required ? 'oui' : 'non'} | ${cellule(parametre.description)} |`
					),
					''
				)
			} else {
				lignes.push('Aucun paramètre.', '')
			}
			lignes.push(`Annotations : ${annotations(outil)}.`)
		}
	}

	lignes.push(
		'',
		'---',
		'',
		'## English',
		'',
		`Version ${data.server.version} of the Basile MCP server exposes **${totaux.tools}** in **${totaux.families}**. Every tool declares a title and the \`readOnlyHint\`, \`destructiveHint\`, \`idempotentHint\` and \`openWorldHint\` annotations. **Read-only** tools only read the Basile database, though searches still use credits; tools that **consume** use the plan export quota or the enrichment balance, so your client may ask you to confirm. No tool is destructive. Full parameter descriptions are in the French section above and in [\`tools.json\`](../tools.json).`,
		'',
		'| Family | Tool | What it does | Main parameters | Cost | Type |',
		'| --- | --- | --- | --- | --- | --- |',
		...familles.flatMap((famille) =>
			famille.outils.map(
				(outil) =>
					`| ${famille.title_en} | \`${outil.name}\` | ${cellule(outil.summary_en)} | ${listeParametresEn(outil)} | ${cellule(outil.cost_en)} | ${natureEn(outil)} |`
			)
		),
		''
	)
	return lignes.join('\n')
}

// ---------------------------------------------------------------------------
// Résumés du README
// ---------------------------------------------------------------------------

function blocFr() {
	return [
		BLOCS.fr[0],
		`Le serveur expose **${totaux.outils}** en **${totaux.familles}**. Chacun annonce son coût dans sa description, pour que l'IA puisse vous prévenir avant de consommer. Le détail de chaque outil, paramètres et annotations compris, est dans [docs/TOOLS.md](docs/TOOLS.md).`,
		'',
		...familles.flatMap((famille) => [
			`**${famille.title}** : ${minuscule(famille.summary)} ([détail](docs/TOOLS.md#${ancre(famille.title)}))`,
			'',
			'| Outil | Ce qu\'il fait | Paramètres principaux | Coût |',
			'| --- | --- | --- | --- |',
			...famille.outils.map(
				(outil) => `| \`${outil.name}\` | ${cellule(outil.summary)} | ${listeParametres(outil)} | ${cellule(outil.cost)} |`
			),
			'',
		]),
		BLOCS.fr[1],
	].join('\n')
}

function blocEn() {
	return [
		BLOCS.en[0],
		`The server exposes **${totaux.tools}** in **${totaux.families}**. Each one states its cost in its description, so the AI can warn you before using credits. See [docs/TOOLS.md](docs/TOOLS.md#english) for parameters and annotations.`,
		'',
		'| Family | Tool | What it does | Cost |',
		'| --- | --- | --- | --- |',
		...familles.flatMap((famille) =>
			famille.outils.map(
				(outil) => `| ${famille.title_en} | \`${outil.name}\` | ${cellule(outil.summary_en)} | ${cellule(outil.cost_en)} |`
			)
		),
		'',
		BLOCS.en[1],
	].join('\n')
}

function remplacerBloc(readme, [debut, fin], contenu) {
	const i = readme.indexOf(debut)
	const j = readme.indexOf(fin)
	if (i === -1 || j === -1 || j < i) {
		console.error(`README.md : repères ${debut} / ${fin} introuvables.`)
		process.exit(1)
	}
	return readme.slice(0, i) + contenu + readme.slice(j + fin.length)
}

const toolsMd = construireToolsMd()
const readme = readFileSync(README, 'utf8')
const nouveauReadme = remplacerBloc(remplacerBloc(readme, BLOCS.fr, blocFr()), BLOCS.en, blocEn())

if (verifier) {
	const problemes = []
	const actuel = existsSync(TOOLS_MD) ? readFileSync(TOOLS_MD, 'utf8') : null
	if (actuel !== toolsMd) problemes.push("docs/TOOLS.md n'est pas à jour.")
	if (nouveauReadme !== readme) problemes.push("Le résumé des outils du README n'est pas à jour.")
	if (problemes.length) {
		console.error([...problemes, 'Lancez "node scripts/generate-tools-md.mjs" et commitez le résultat.'].join('\n'))
		process.exit(1)
	}
	console.log(`docs/TOOLS.md et le README correspondent à tools.json (${totaux.outils}).`)
} else {
	mkdirSync(dirname(TOOLS_MD), { recursive: true })
	writeFileSync(TOOLS_MD, toolsMd)
	writeFileSync(README, nouveauReadme)
	console.log(`docs/TOOLS.md et le résumé des outils du README sont écrits (${totaux.outils}).`)
}
